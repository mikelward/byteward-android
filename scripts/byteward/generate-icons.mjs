#!/usr/bin/env node
// Generates Byteward's Android launcher icons and logo drawables as vector
// drawables, from the portcullis mark in marks.mjs and the outlined wordmark
// in wordmark.json.
//
// marks.mjs, wordmark.json and SpaceGrotesk-OFL.txt are copies of the files in
// byteward-clients' scripts/byteward, which is where the mark is designed;
// copy them across when it changes, then run (from the repository root):
//
//   node scripts/byteward/generate-icons.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { portcullis } from "./marks.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const wordmark = JSON.parse(readFileSync(join(here, "wordmark.json"), "utf8"));

const HEADER = "<!-- Generated by scripts/byteward/generate-icons.mjs. Do not edit by hand. -->";
const f = (n) => Number(n.toFixed(4));

/** A group transform that fits the mark's box into a square of `size` centred at (cx, cy). */
function fit(size, cx, cy) {
  const [bx, by, bw, bh] = portcullis.box;
  const scale = size / Math.max(bw, bh);
  return {
    scale: f(scale),
    tx: f(cx - (bx + bw / 2) * scale),
    ty: f(cy - (by + bh / 2) * scale),
  };
}

function vector({ width, height, viewportWidth, viewportHeight, body, tint }) {
  return `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${width}dp"
    android:height="${height}dp"
${tint ? `    android:tint="${tint}"\n` : ""}    android:viewportWidth="${viewportWidth}"
    android:viewportHeight="${viewportHeight}">
${body}
</vector>
`;
}

function markGroup({ size, cx, cy, fill, path = portcullis.path }) {
  const t = fit(size, cx, cy);
  return `    <group
        android:scaleX="${t.scale}"
        android:scaleY="${t.scale}"
        android:translateX="${t.tx}"
        android:translateY="${t.ty}">
        <path
            android:fillColor="${fill}"
            android:pathData="${path}" />
    </group>`;
}

function write(relativePath, contents) {
  writeFileSync(join(root, relativePath), contents);
  console.log(`wrote ${relativePath}`);
}

// Adaptive launcher icon layers: a 108 dp canvas whose middle 66 dp is the
// safe zone every launcher mask keeps. The mark sits inside it with margin.
const launcherForeground = vector({
  width: 108,
  height: 108,
  viewportWidth: 108,
  viewportHeight: 108,
  body: markGroup({ size: 52, cx: 54, cy: 54, fill: "#FFFFFF" }),
});
for (const sourceSet of ["main", "release", "beta"]) {
  write(`app/src/${sourceSet}/res/drawable/ic_launcher_foreground.xml`, launcherForeground);
  write(`app/src/${sourceSet}/res/drawable/ic_launcher_monochrome.xml`, launcherForeground);
}

// The splash screen icon, on the same 108 dp canvas.
write("ui/src/main/res/drawable/logo_shield_icon.xml", launcherForeground);

// The app icon as a single drawable, used by autofill suggestions and the
// credential exchange registry: a black rounded square with a white mark.
write(
  "ui/src/main/res/drawable/logo_bitwarden_icon.xml",
  vector({
    width: 1024,
    height: 1024,
    viewportWidth: 1024,
    viewportHeight: 1024,
    body:
      `    <path
        android:fillColor="#111111"
        android:pathData="M225 0H799A225 225 0 0 1 1024 225V799A225 225 0 0 1 799 1024H225A225 225 0 0 1 0 799V225A225 225 0 0 1 225 0Z" />\n` +
      markGroup({ size: 700, cx: 512, cy: 512, fill: "#FFFFFF" }),
  }),
);

// The small single-colour icon, tinted wherever it is used. Toolbar-sized, so
// it uses the simpler version of the mark.
write(
  "ui/src/main/res/drawable/ic_shield.xml",
  vector({
    width: 20,
    height: 20,
    viewportWidth: 20,
    viewportHeight: 20,
    body: markGroup({ size: 18, cx: 10, cy: 10, fill: "#000000", path: portcullis.smallPath }),
  }),
);

// The horizontal logo on the landing and registration screens: the mark then
// the wordmark, in a colour that follows the light or dark theme.
{
  const height = 34;
  const [bx, by, bw, bh] = portcullis.box;
  const markScale = height / bh;
  const markWidth = bw * markScale;
  const [wx, wy, ww, wh] = wordmark.viewBox;
  const wordScale = (height * 0.8) / wh;
  const gap = 9;
  const width = Math.ceil(markWidth + gap + ww * wordScale);
  write(
    "ui/src/main/res/drawable/logo_bitwarden.xml",
    vector({
      width,
      height,
      viewportWidth: width,
      viewportHeight: height,
      body:
        `    <group
        android:scaleX="${f(markScale)}"
        android:scaleY="${f(markScale)}"
        android:translateX="${f(-bx * markScale)}"
        android:translateY="${f(-by * markScale)}">
        <path
            android:fillColor="@color/byteward_logo"
            android:pathData="${portcullis.path}" />
    </group>
    <group
        android:scaleX="${f(wordScale)}"
        android:scaleY="${f(wordScale)}"
        android:translateX="${f(markWidth + gap - wx * wordScale)}"
        android:translateY="${f((height - wh * wordScale) / 2 - wy * wordScale)}">
        <path
            android:fillColor="@color/byteward_logo"
            android:pathData="${wordmark.d}" />
    </group>`,
    }),
  );
}
